/**
 * QA-02 (attemptId pass-through), QA-01 (amount untouched), QA-11 (failure passed through unchanged,
 * no wrapping/leak), QA-09 (what the app logs on MQTT failure).
 */
class AppQrisDependenciesPassThroughTest {
    private class Recording(private val result: CashupResult<GeneratedQr>) : QrisGateway {
        data class Call(val host: Int, val amount: Money, val attemptId: String)
        val calls = mutableListOf<Call>()
        override suspend fun payApps(): CashupResult<List<PayApp>> = CashupResult.Success(emptyList())
        override suspend fun generate(qrisHostId: Int, amount: Money, attemptId: String): CashupResult<GeneratedQr> {
            calls += Call(qrisHostId, amount, attemptId)
            return result
        }
        override suspend fun inquiry(transactionId: String): CashupResult<QrisPaymentResult> = error("unused")
    }

    private class Transport(private val failWith: Exception? = null) : PaymentNotificationTransport {
        override val isConnected = false
        override fun connect(deviceId: String) { failWith?.let { throw it } }
        override val messages: Flow<RawNotification> = emptyFlow()
        override fun disconnect() = Unit
    }

    private val idr = Currency("IDR", 0)

    private fun failure() = CashupResult.Failure(CashupError.Network("NET", "down"))

    private fun deps(gateway: QrisGateway, transport: Transport = Transport()) = AppQrisDependencies(
        gateway = gateway,
        tracker = QrisPaymentTracker(gateway, NotificationQrisSignalSource(PaymentStatusWaiter(transport), transport), GsonPushParser()),
        transport = transport,
        deviceId = { "dev-1" },
        transactionAllowed = { true },
        io = Dispatchers.Unconfined,
    )

    @Before fun mockLog() {
        mockkStatic(Log::class)
    }

    @After fun unmockLog() {
        unmockkStatic(Log::class)
    }

    @Test fun `generate forwards host id, amount and the same attemptId unchanged`() = runBlocking {
        val gw = Recording(failure())
        val amount = Money(12_345L, idr)
        deps(gw).generate(7, amount, "attempt-abc")
        assertEquals(listOf(Recording.Call(7, amount, "attempt-abc")), gw.calls)
    }

    @Test fun `a repeated attemptId is forwarded as is and never regenerated by the app`() = runBlocking {
        val gw = Recording(failure())
        val d = deps(gw)
        d.generate(1, Money(1L, idr), "same-attempt")
        d.generate(1, Money(1L, idr), "same-attempt")
        assertEquals(listOf("same-attempt", "same-attempt"), gw.calls.map { it.attemptId })
    }

    @Test fun `boundary amounts 0 and Long MAX are not altered by the app layer`() = runBlocking {
        val gw = Recording(failure())
        val d = deps(gw)
        d.generate(1, Money(0L, idr), "a")
        d.generate(1, Money(Long.MAX_VALUE, idr), "b")
        assertEquals(listOf(0L, Long.MAX_VALUE), gw.calls.map { it.amount.minor })
    }

    @Test fun `a gateway failure is returned as the same instance with code and status untouched`() = runBlocking {
        val failure = CashupResult.Failure(CashupError.Remote("PAYMENT_DUPLICATE", "duplicate", 409))
        val result = deps(Recording(failure)).generate(1, Money(1L, idr), "k1")
        assertSame(failure, result)
        val err = (result as CashupResult.Failure).error
        assertEquals("PAYMENT_DUPLICATE", err.code)
        assertEquals(409, (err as CashupError.Remote).httpStatus)
    }

    @Test fun `mqtt connect failure logs one warning without the device id`() {
        val logged = mutableListOf<String>()
        every { Log.w(any<String>(), any<String>()) } answers { logged += secondArg<String>(); 0 }
        runBlocking {
            deps(Recording(failure()), Transport(IllegalStateException("broker unreachable"))).ensureNotificationsConnected()
        }
        assertEquals(1, logged.size)
        assertTrue(logged[0], !logged[0].contains("dev-1"))
        // Public Visa test number; must never appear in app logs.
        assertTrue(logged[0], !logged[0].contains("4111111111111111")) // pan-ok
    }
}
